-- LUMI: sinalização segura para chamadas de voz/vídeo WebRTC.
-- Execute no Supabase > SQL Editor, depois de direct-messages-and-files.sql.
-- Não apaga tabelas nem mensagens existentes.

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  signal_type text not null check (signal_type in ('offer','answer','ice','end','busy')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint call_signals_no_self_call check (sender_id <> recipient_id)
);

create index if not exists idx_call_signals_recipient_created
  on public.call_signals(recipient_id, created_at desc);

alter table public.call_signals enable row level security;

drop policy if exists "Conversation members can read call signals addressed to them" on public.call_signals;
create policy "Conversation members can read call signals addressed to them"
on public.call_signals for select to authenticated
using (
  recipient_id = auth.uid()
  and exists (select 1 from public.conversation_members cm where cm.conversation_id = call_signals.conversation_id and cm.user_id = auth.uid())
);

drop policy if exists "Conversation members can send call signals" on public.call_signals;
create policy "Conversation members can send call signals"
on public.call_signals for insert to authenticated
with check (
  sender_id = auth.uid()
  and exists (select 1 from public.conversation_members cm where cm.conversation_id = call_signals.conversation_id and cm.user_id = auth.uid())
  and exists (select 1 from public.conversation_members cm where cm.conversation_id = call_signals.conversation_id and cm.user_id = call_signals.recipient_id)
);

-- Realtime precisa observar os novos sinais para tocar/atender chamadas.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'call_signals'
  ) then
    alter publication supabase_realtime add table public.call_signals;
  end if;
exception when duplicate_object then null;
end $$;
